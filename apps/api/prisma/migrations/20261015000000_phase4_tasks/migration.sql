-- Phase 4 — projects, tasks, Gantt (brief §6). Partial indexes are raw SQL (ADR-002);
-- the baseline columns are Prisma-generated.

-- Every task read and write filters the live tasks of one project.
CREATE INDEX tasks_project_live_idx
  ON tasks (project_id)
  WHERE archived_at IS NULL;

-- The daily reminder job (TASK_DUE_SOON / TASK_OVERDUE): open, assigned, live tasks by end date.
CREATE INDEX tasks_due_reminder_idx
  ON tasks (end_date)
  WHERE archived_at IS NULL AND assignee_id IS NOT NULL AND status <> 'DONE';

-- "My tasks": a supervisor's live assigned tasks by end date.
CREATE INDEX tasks_assignee_live_idx
  ON tasks (assignee_id, end_date)
  WHERE archived_at IS NULL;

-- Task attachments: files linked to a task.
CREATE INDEX files_task_idx
  ON files (entity_id)
  WHERE entity_type = 'task' AND deleted_at IS NULL;

