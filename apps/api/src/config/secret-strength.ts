/**
 * Start-up checks for secrets (security review H1, ADR-061).
 * `.env.example` ships values that contain `CHANGE_ME`; a copied but unedited file must never
 * boot in production. Secrets that sign or encrypt must also look random, not typed by hand.
 */

export const PLACEHOLDER_RE = /change[_-]?me/i;

export function isPlaceholder(value: string | undefined | null): boolean {
  return !!value && PLACEHOLDER_RE.test(value);
}

/** Shannon entropy in bits per symbol. */
export function shannonBitsPerSymbol(symbols: ArrayLike<number | string>): number {
  const n = symbols.length;
  if (!n) return 0;
  const counts = new Map<number | string, number>();
  for (let i = 0; i < n; i++) counts.set(symbols[i]!, (counts.get(symbols[i]!) ?? 0) + 1);
  let bits = 0;
  for (const c of counts.values()) {
    const p = c / n;
    bits -= p * Math.log2(p);
  }
  return bits;
}

const BASE64_RE = /^[A-Za-z0-9+/_-]+={0,2}$/;

/**
 * A signing secret generated by `openssl rand -base64 48` (or any base64 of ≥ 32 random bytes).
 * Rejects placeholders, non-base64 text and hand-typed phrases (low per-character entropy).
 * Returns the reason, or null when the value is acceptable.
 */
export function weakRandomSecretReason(value: string, minBytes = 32): string | null {
  if (isPlaceholder(value)) return 'is still the CHANGE_ME placeholder';
  const v = value.trim();
  if (!BASE64_RE.test(v)) return 'must be base64 (generate with: openssl rand -base64 48)';
  const bytes = Buffer.from(v.replace(/-/g, '+').replace(/_/g, '/'), 'base64');
  if (bytes.length < minBytes) return `must decode to at least ${minBytes} random bytes (openssl rand -base64 48)`;
  const chars = [...v.replace(/=+$/, '')];
  // Best effort against hand-typed values. Random base64 of 32+ bytes (43+ chars) always mixes
  // upper and lower case (a miss is ~1e-10) and scores ≥ 4 bits/char (lowest of 200k samples:
  // 4.04); repeats, single-case words and short alphabets fail. It cannot recognise every
  // memorable phrase: generate the value with openssl, as .env.example says.
  if (
    new Set(chars).size < 16 ||
    !/[A-Z]/.test(v) ||
    !/[a-z]/.test(v) ||
    shannonBitsPerSymbol(chars) < 3.8
  ) {
    return 'looks hand-typed or repetitive; use random bytes (openssl rand -base64 48)';
  }
  return null;
}

/** A 32-byte key (already length-checked) whose bytes must look random: no zero/repeated keys. */
export function weakKeyBytesReason(key: Buffer): string | null {
  if (new Set(key).size < 16) return 'key bytes are not random (openssl rand -base64 32)';
  return null;
}

/** Passwords / access keys that are not base64 keys: reject placeholders and trivially short values. */
export function weakPasswordReason(value: string, minLength: number): string | null {
  if (isPlaceholder(value)) return 'is still the CHANGE_ME placeholder';
  if (value.length < minLength) return `must be at least ${minLength} characters`;
  return null;
}
